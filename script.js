// 3. ฟังก์ชันคำนวณและประมวลผลจัดอันดับ TOP 20
function generateRecommendation() {
  const selectedSoil = document.getElementById('soil-select').value;
  const selectedProvince = document.getElementById('province-select').value;

  const resultSection = document.getElementById('result-section');
  const tableBody = document.getElementById('crop-table-body');
  const resultTitle = document.getElementById('result-title');
  const climateInfo = document.getElementById('climate-info');

  // ดึงข้อมูลภูมิอากาศจังหวัด
  const provinceData = regionClimateMap[selectedProvince] || { region: "กลาง", climate: "อบอุ่นชื้น มรสุมตามฤดูกาล" };

  // คัดแยกและคำนวณคะแนนความเหมาะสม (Score Calculator Algorithm)
  const scoredCrops = masterCrops.map(crop => {
    let score = 0;

    // คะแนนความเข้ากันของดิน (50 คะแนน)
    if (crop.suitableSoils.includes(selectedSoil)) {
      score += 50;
    } else {
      score += 20; // คะแนนพื้นฐาน
    }

    // คะแนนปรับตามภูมิภาคและสภาพอากาศ (50 คะแนน)
    if (provinceData.region === "ใต้" && (crop.name.includes("ยางพารา") || crop.name.includes("ปาล์ม") || crop.name.includes("มังคุด"))) {
      score += 40;
    } else if (provinceData.region === "เหนือ" && (crop.name.includes("สลัด") || crop.name.includes("มะเขือเทศ") || crop.name.includes("สตอเบอร์รี่"))) {
      score += 40;
    } else if (provinceData.region === "อีสาน" && (crop.name.includes("มันสำปะหลัง") || crop.name.includes("อ้อย") || crop.name.includes("แตงโม"))) {
      score += 40;
    } else if (provinceData.region === "ตะวันออก" && (crop.name.includes("ทุเรียน") || crop.name.includes("มังคุด") || crop.name.includes("เงาะ"))) {
      score += 40;
    } else {
      score += 25;
    }

    return { ...crop, score };
  });

  // จัดเรียงคะแนนจากมากไปน้อย (Top 20)
  scoredCrops.sort((a, b) => b.score - a.score);

  // แสดงหัวข้อและสภาพอากาศ
  resultTitle.innerText = `ตารางจัดอันดับ TOP 20 พืชที่เหมาะสมสำหรับจังหวัด${selectedProvince}`;
  climateInfo.innerHTML = `🌤️ <strong>สภาพอากาศประจำจังหวัด (${provinceData.region}):</strong> ${provinceData.climate}`;

  // แสดงผลลงตาราง
  tableBody.innerHTML = "";
  scoredCrops.forEach((crop, index) => {
    const row = document.createElement('tr');
    row.innerHTML = `
      <td style="text-align: center;"><span class="badge-rank">${index + 1}</span></td>
      <td><strong>${crop.name}</strong></td>
      <td>${crop.reasons}</td>
      <td>💧 ${crop.water}</td>
      <td>☀️ ${crop.sun}</td>
      <td>🗓️ ${crop.season}</td>
      <td>🛠️ ${crop.howToGrow}</td>
    `;
    tableBody.appendChild(row);
  });

  // เปิดแสดงผลกล่อง
  resultSection.classList.remove('hidden');
  resultSection.scrollIntoView({ behavior: 'smooth' });
}

